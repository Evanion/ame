-- Collect every L["..."] / L['...'] key used in the addon's Lua files and write Locales/enUS.lua (keys = true).
--   lua5.1 scripts/locale-keys.lua            write Locales/enUS.lua
--   lua5.1 scripts/locale-keys.lua --check    fail if Locales/enUS.lua is out of date
-- Keys must be single string literals inside L[...] (one line). Files: the .lua files listed in the TOC under Core\.
-- Writing also drops translations of keys the code no longer uses from the other locales (then run stylua).
local check = arg[1] == "--check"

local function readAll(path)
  local f = assert(io.open(path, "rb"))
  local s = f:read("*a")
  f:close()
  return s
end

local files = {}
for line in io.lines("AzerothMercantileExchange.toc") do
  line = line:gsub("\r", "")
  if line:match("^Core\\.*%.lua$") then
    files[#files + 1] = (line:gsub("\\", "/"))
  end
end

-- Every L["..."] / L['...'] string literal in src, as source text (escapes kept). Scanned character by character:
-- a Lua pattern can't tell where a string with escapes ends, and with several keys on one line it ran past the first
-- closing quote and swallowed the next key.
local function literals(src)
  local out, pos = {}, 1
  while true do
    local _, e, quote = src:find("%f[%w_]L%[%s*([\"'])", pos)
    if not e then
      return out
    end
    local i, parts = e + 1, { quote }
    while true do
      local c = src:sub(i, i)
      if c == "" or c == "\n" then
        parts = nil -- unterminated on this line: not a key
        break
      elseif c == "\\" then
        parts[#parts + 1] = src:sub(i, i + 1)
        i = i + 2
      else
        parts[#parts + 1] = c
        i = i + 1
        if c == quote then
          break
        end
      end
    end
    if parts and src:find("^%s*%]", i) then
      out[#out + 1] = table.concat(parts)
    end
    pos = i
  end
end

local keys, seen = {}, {}
for _, path in ipairs(files) do
  for _, literal in ipairs(literals(readAll(path))) do
    local ok, value = pcall(loadstring("return " .. literal))
    if ok and type(value) == "string" and not seen[value] then
      seen[value] = true
      keys[#keys + 1] = value
    end
  end
end
table.sort(keys)

local out = {
  '-- English (default). Keys are the English texts; generated by scripts/locale-keys.lua from the L["..."] calls in',
  "-- the code - don't edit by hand, run the script after changing texts.",
  "local ADDON = ...",
  'local AceLocale = LibStub and LibStub("AceLocale-3.0", true)',
  'local L = AceLocale and AceLocale:NewLocale(ADDON, "enUS", true, true)',
  "if not L then",
  "  return",
  "end",
  "",
}
for _, key in ipairs(keys) do
  out[#out + 1] = ("L[%q] = true"):format(key):gsub("\\\n", "\\n")
end
local text = table.concat(out, "\n") .. "\n"

if check then
  if readAll("Locales/enUS.lua") ~= text then
    io.stderr:write("Locales/enUS.lua is out of date: run lua5.1 scripts/locale-keys.lua\n")
    os.exit(1)
  end
  print(("%d keys, enUS up to date"):format(#keys))
else
  local f = assert(io.open("Locales/enUS.lua", "wb"))
  f:write(text)
  f:close()
  print(("%d keys written to Locales/enUS.lua"):format(#keys))

  -- Translations of texts the code no longer uses are dropped (each locale is loaded with a stub AceLocale and
  -- rewritten: its header, then its translations in enUS order). Run stylua on Locales afterwards.
  local LOCALES = { "deDE", "frFR", "esES", "ruRU", "ptBR", "itIT", "koKR", "zhCN", "zhTW" }
  for _, code in ipairs(LOCALES) do
    local path = "Locales/" .. code .. ".lua"
    local src = readAll(path)
    local strings = {}
    _G.LibStub = function()
      return {
        NewLocale = function()
          return strings
        end,
      }
    end
    assert(loadstring(src, path))("AzerothMercantileExchange", {})
    local stale = 0
    for key in pairs(strings) do
      if not seen[key] then
        stale = stale + 1
      end
    end
    do -- always rewritten: enUS order in every locale, whatever was appended
      local head = src:match("^(.-\nif not L then\n  return\nend\n)")
      assert(head, path .. ": header not found")
      local lines = { head }
      for _, key in ipairs(keys) do
        if strings[key] then
          local line = ("L[%q] = %q"):format(key, strings[key]):gsub("\\\n", "\\n")
          lines[#lines + 1] = line
        end
      end
      local file = assert(io.open(path, "wb"))
      file:write(table.concat(lines, "\n") .. "\n")
      file:close()
      if stale > 0 then
        print(("%s: dropped %d unused translations"):format(code, stale))
      end
    end
  end
end
