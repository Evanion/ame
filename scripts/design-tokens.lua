-- Writes docs/ux/design/tokens.css from docs/ux/design/tokens.lua: the colours and fonts as CSS variables on .ame,
-- each faction theme's accent with the shades derived from it (.ame.th-horde / .th-alliance / .th-goblin), and the
-- player's own faction colour (.ame.fa-horde / .fa-alliance).
--   lua5.1 scripts/design-tokens.lua
local T = dofile("docs/ux/design/tokens.lua")

local function lin(v)
  v = v / 255
  return v <= 0.03928 and v / 12.92 or ((v + 0.055) / 1.055) ^ 2.4
end
local function luminance(c)
  return 0.2126 * lin(c[1]) + 0.7152 * lin(c[2]) + 0.0722 * lin(c[3])
end
-- the accent darkened until white text on it reaches `ratio` (as W.PrimaryShade in the addon)
local function primary(c, ratio)
  for step = 100, 0, -1 do
    local s = { c[1] * step / 100, c[2] * step / 100, c[3] * step / 100 }
    if 1.05 / (luminance(s) + 0.05) >= ratio then
      return s
    end
  end
  return { 0, 0, 0 }
end
local function rgb(c)
  return ("rgb(%d,%d,%d)"):format(math.floor(c[1] + 0.5), math.floor(c[2] + 0.5), math.floor(c[3] + 0.5))
end
local function kebab(s)
  return (s:gsub("(%u)", function(u)
    return "-" .. u:lower()
  end):gsub("(%a)(%d)", "%1%2"))
end

local function accentVars(theme)
  local a = theme.accent
  local sel = { a[1] * T.selectedShade, a[2] * T.selectedShade, a[3] * T.selectedShade }
  return {
    "--acc:" .. rgb(a),
    "--acc-sel:" .. rgb(sel),
    "--acc-pri:" .. rgb(primary(a, T.primaryContrast)),
    ("--acc-row:rgba(%d,%d,%d,%s)"):format(a[1], a[2], a[3], T.rowAlpha),
  }
end

local out = { "/* generated by scripts/design-tokens.lua from tokens.lua: don't edit */" }
local base = {}
local keys = {}
for k in pairs(T.color) do
  keys[#keys + 1] = k
end
table.sort(keys)
for _, k in ipairs(keys) do
  base[#base + 1] = "--" .. kebab(k) .. ":" .. T.color[k]
end
base[#base + 1] = "--font-ui:" .. T.font.ui
base[#base + 1] = "--font-display:" .. T.font.display
for _, v in ipairs(accentVars(T.themes[1])) do -- the default theme
  base[#base + 1] = v
end
base[#base + 1] = "--faction:" .. rgb(T.factions[1].color) -- the default faction
out[#out + 1] = ".ame{" .. table.concat(base, ";") .. "}"
for _, theme in ipairs(T.themes) do
  out[#out + 1] = ".ame.th-" .. theme.key .. "{" .. table.concat(accentVars(theme), ";") .. "}"
end

for _, faction in ipairs(T.factions) do
  out[#out + 1] = ".ame.fa-" .. faction.key .. "{--faction:" .. rgb(faction.color) .. "}"
end

local f = assert(io.open("docs/ux/design/tokens.css", "wb"))
f:write(table.concat(out, "\n") .. "\n")
f:close()
print("docs/ux/design/tokens.css written")
