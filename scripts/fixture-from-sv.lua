-- Build a small real-data test fixture from AME's SavedVariables (market data only: no character names, no ledger).
--   lua5.1 scripts/fixture-from-sv.lua "<WTF/Account/NAME/SavedVariables>" [shard] [items]
-- Writes spec/fixtures/market.lua: for a subset of items (default 120) of one auction house (default: the one with
-- the most history), their daily price series, pricing profiles and vendor prices (saved with the market index from
-- version 0.2.0-beta.3 on). Picks a mix: up to 15 items per rare signal (BUY / SELL / WAIT / VENDOR), the
-- most-traded, some HOLD and some thin ones. Needs Libs/LibDeflate (scripts/fetch-libs.sh).
local dir, wantShard, wanted = arg[1], arg[2], tonumber(arg[3]) or 120
assert(dir, "usage: lua5.1 scripts/fixture-from-sv.lua <SavedVariables dir> [shard] [items]")

dofile(dir .. "/AzerothMercantileExchange.lua")
dofile(dir .. "/AzerothMercantileExchange_History.lua")

local ns = {}
for _, f in ipairs({ "Core/Init.lua", "Core/Codec.lua", "Core/Compress.lua", "Core/Analytics.lua", "Core/Store.lua" }) do
  assert(loadfile(f))("AzerothMercantileExchange", ns)
end
assert(loadfile("Core/MarketIndex.lua"))("AzerothMercantileExchange", ns)
local LibDeflate = dofile("Libs/LibDeflate/LibDeflate.lua")
local compressor = ns.Compress.New(LibDeflate)

-- the auction house with the most days of history, unless named
local shard, data = wantShard, wantShard and AME_HistoryDB.shards[wantShard]
if not data then
  local best = -1
  for key, d in pairs(AME_HistoryDB.shards) do
    local n = 0
    for _ in pairs(d.days or {}) do
      n = n + 1
    end
    if n > best then
      shard, data, best = key, d, n
    end
  end
end
assert(data, "no history for " .. tostring(shard))
local store = ns.Store.New(data, {
  compressor = compressor,
  now = function()
    return os.time()
  end,
})

-- the saved index says which items have which signal, and their vendor prices
local saved = AME_DB.indexCache and AME_DB.indexCache[shard]
local index = saved and ns.MarketIndex.Decode(saved.s)
assert(index, "no saved market index for " .. shard .. " (log out once with this version to save one)")

local all = {}
for _, s in pairs(index.items) do
  all[#all + 1] = s
end
table.sort(all, function(a, b)
  if (a.days or 0) ~= (b.days or 0) then
    return (a.days or 0) > (b.days or 0)
  end
  return a.itemID < b.itemID
end)
local picked, chosen = {}, {}
local function pick(s)
  if s and not chosen[s.itemID] and #picked < wanted then
    chosen[s.itemID] = true
    picked[#picked + 1] = s
  end
end
local RARE, perSignal = { buy = true, sell = true, wait = true, vendor = true }, {}
for _, s in ipairs(all) do -- the rare signals, up to 15 items each
  if RARE[s.signal] and (perSignal[s.signal] or 0) < 15 then
    perSignal[s.signal] = (perSignal[s.signal] or 0) + 1
    pick(s)
  end
end
local liquid = math.floor((wanted - #picked) / 2)
for i = 1, liquid do -- the most-traded
  pick(all[i])
end
for i = #all, 1, -math.max(1, math.floor(#all / wanted)) do -- a spread of the rest, thin ones included
  pick(all[i])
end

local function num(x)
  if x == math.floor(x) then
    return tostring(x)
  end
  return ("%.6g"):format(x)
end

local out = {
  "-- Real market data for specs: a subset of one auction house's history (generated by scripts/fixture-from-sv.lua;",
  "-- market data only). points: { day, min, market, median, qty, scans, high, drain, obs } per day.",
  "return {",
  ("  shard = %q,"):format(shard:gsub("^[^|]*", "Market")),
  ("  day = %d,"):format(index.day),
  "  items = {",
}
table.sort(picked, function(a, b)
  return a.itemID < b.itemID
end)
for _, s in ipairs(picked) do
  local id = s.itemID
  local points = {}
  for _, p in ipairs(store:Series(id, index.day - 29, index.day)) do
    points[#points + 1] = ("{%s}"):format(table.concat({
      num(p.day),
      num(p.min),
      num(p.market),
      num(p.median or p.market),
      num(p.qty or 0),
      num(p.scans or 1),
      num(p.high or 0),
      num(p.drain or 0),
      num(p.obs or 0),
    }, ","))
  end
  local profile = AME_DB.pricing and AME_DB.pricing[shard] and AME_DB.pricing[shard][id]
  out[#out + 1] = ("    [%d] = { signal = %q, vendor = %s, profile = %s, points = { %s } },"):format(
    id,
    s.signal or "none",
    s.vendorPrice and num(s.vendorPrice) or "nil",
    profile and ("%q"):format(profile) or "nil",
    table.concat(points, ", ")
  )
end
out[#out + 1] = "  },"
out[#out + 1] = "}"
local f = assert(io.open("spec/fixtures/market.lua", "wb"))
f:write(table.concat(out, "\n") .. "\n")
f:close()
print(("%d items from %s written to spec/fixtures/market.lua"):format(#picked, shard))
